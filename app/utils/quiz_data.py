# Критерии оценки
def get_grade(score: int) -> Tuple[str, str]:
    """
    Возвращает оценку и комментарий в зависимости от количества правильных ответов
    """
    if score >= 9:
        return "Отлично! 🏆", "Вы отлично разбираетесь в информатике!"
    elif score >= 7:
        return "Хорошо! ⭐", "У вас хорошие знания по информатике!"
    elif score >= 5:
        return "Удовлетворительно ✅", "Неплохо, но стоит повторить некоторые темы."
    else:
        return "Стоит повторить материал 📚", "Рекомендуем еще раз изучить основы информатики."
